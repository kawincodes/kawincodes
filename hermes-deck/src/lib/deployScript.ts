import { assertEnvEntry, shq } from './shell';

export const HERMES_IMAGE = 'nousresearch/hermes-agent';
export const API_PORT = 8642;

export interface DockerDeployOptions {
  /** Environment variable that carries the provider key, e.g. OPENROUTER_API_KEY. */
  providerEnv: string;
  providerKey: string;
  /** Hermes `model.provider` value. */
  providerId: string;
  model: string;
  /** Bearer token for the Hermes API server (API_SERVER_KEY). */
  apiServerKey: string;
  imageTag: 'latest' | 'main';
  container: string;
  dataDir: string;
  hostPort: number;
}

export const DEPLOY_STEPS = [
  { id: 'preflight', label: 'Check server' },
  { id: 'docker', label: 'Install Docker' },
  { id: 'config', label: 'Write agent config' },
  { id: 'pull', label: 'Pull Hermes image' },
  { id: 'configure', label: 'Set model' },
  { id: 'start', label: 'Start gateway' },
  { id: 'health', label: 'Health check' },
] as const;

export type DeployStepId = (typeof DEPLOY_STEPS)[number]['id'];

const CONTAINER_NAME = /^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,62}$/;
const MODEL_NAME = /^[A-Za-z0-9._:/@+-]{1,200}$/;

export function validateDockerOptions(o: DockerDeployOptions): void {
  assertEnvEntry(o.providerEnv, o.providerKey);
  assertEnvEntry('API_SERVER_KEY', o.apiServerKey);
  if (o.apiServerKey.length < 16) throw new Error('API server key must be at least 16 characters.');
  if (!MODEL_NAME.test(o.model)) throw new Error('Model id contains unsupported characters.');
  if (!/^[a-z0-9-]+$/.test(o.providerId)) throw new Error('Invalid provider id.');
  if (!CONTAINER_NAME.test(o.container)) throw new Error('Invalid container name.');
  if (!o.dataDir.startsWith('/') || o.dataDir.includes('\n')) throw new Error('Data directory must be an absolute path.');
  if (!Number.isInteger(o.hostPort) || o.hostPort < 1 || o.hostPort > 65535) throw new Error('Invalid port.');
}

/** Shared shell prelude: strict mode, progress markers the app parses, and an HTTP helper. */
function prelude(o: Pick<DockerDeployOptions, 'container' | 'dataDir' | 'hostPort' | 'imageTag'>): string {
  return `#!/usr/bin/env bash
# Generated by Hermes Deck. Runs as root on the target server.
# Run it from a file (bash deploy.sh), not through stdin: stdin is detached below so no
# child process can read the sudo password line that may still be buffered there.
set -Eeuo pipefail
exec </dev/null
umask 022

HD_IMAGE=${shq(`${HERMES_IMAGE}:${o.imageTag}`)}
HD_NAME=${shq(o.container)}
HD_DATA_DIR=${shq(o.dataDir)}
HD_PORT=${o.hostPort}

step() { printf '::step::%s\\n' "$1"; }
fail() { printf '::fail::%s\\n' "$1"; exit 1; }
trap 'fail "command failed (line $LINENO): $BASH_COMMAND"' ERR
http_get() {
  if command -v curl >/dev/null 2>&1; then curl -fsSL --max-time 10 "$1"
  elif command -v wget >/dev/null 2>&1; then wget -qO- -T 10 "$1"
  else return 127; fi
}
`;
}

/** Starts the container (API bound to the server's loopback only) and waits for /health. */
function startAndWait(): string {
  return `
step start
docker rm -f "$HD_NAME" >/dev/null 2>&1 || true
docker run -d --name "$HD_NAME" --restart unless-stopped \\
  -v "$HD_DATA_DIR:/opt/data" \\
  -p "127.0.0.1:$HD_PORT:8642" \\
  "$HD_IMAGE" gateway run >/dev/null
echo "Container $HD_NAME started; API server published on 127.0.0.1:$HD_PORT (reachable over SSH only)."

step health
for _ in $(seq 1 120); do
  if http_get "http://127.0.0.1:$HD_PORT/health" >/dev/null 2>&1; then
    echo "Hermes API server is healthy."
    printf '::ok::%s\\n' "$(docker inspect -f '{{.Config.Image}}' "$HD_NAME")"
    exit 0
  fi
  if [ "$(docker inspect -f '{{.State.Running}}' "$HD_NAME" 2>/dev/null)" != "true" ]; then
    docker logs --tail 80 "$HD_NAME" 2>&1 || true
    fail "The container stopped during startup (see the log above)."
  fi
  sleep 2
done
docker logs --tail 80 "$HD_NAME" 2>&1 || true
fail "Timed out waiting for http://127.0.0.1:$HD_PORT/health"
`;
}

/**
 * Full install: Docker (if missing), `.env` with the provider and API server keys, model
 * selection, then a supervised `gateway run` container. Re-running it is safe: it keeps any other
 * settings already in `.env` (for example Telegram tokens added later with `hermes gateway setup`).
 */
export function buildDockerDeployScript(o: DockerDeployOptions): string {
  validateDockerOptions(o);
  const managed = ['API_SERVER_ENABLED', 'API_SERVER_HOST', 'API_SERVER_PORT', 'API_SERVER_KEY', o.providerEnv];
  return `${prelude(o)}
step preflight
[ "$(id -u)" -eq 0 ] || fail "Root privileges are required (log in as root or allow sudo)."
if [ -r /etc/os-release ]; then echo "OS: $(. /etc/os-release && echo "\${PRETTY_NAME:-unknown}")"; fi
ARCH="$(uname -m)"
echo "Architecture: $ARCH"
case "$ARCH" in
  x86_64|amd64|aarch64|arm64) ;;
  *) fail "Unsupported CPU architecture $ARCH: the Hermes image is published for amd64 and arm64." ;;
esac

step docker
if ! command -v docker >/dev/null 2>&1; then
  echo "Docker not found. Installing it with the official script from get.docker.com ..."
  installer="$(mktemp)"
  http_get https://get.docker.com > "$installer" || fail "Could not download get.docker.com (curl or wget is required)."
  sh "$installer"
  rm -f "$installer"
fi
if command -v systemctl >/dev/null 2>&1; then systemctl enable --now docker >/dev/null 2>&1 || true; fi
docker info >/dev/null 2>&1 || fail "Docker is installed but its daemon is not running."
docker --version

step config
mkdir -p "$HD_DATA_DIR"
chmod 700 "$HD_DATA_DIR"
ENV_FILE="$HD_DATA_DIR/.env"
touch "$ENV_FILE"
chmod 600 "$ENV_FILE"
merged="$(mktemp)"
grep -vE '^(${managed.join('|')})=' "$ENV_FILE" > "$merged" || true
cat >> "$merged" <<'HERMES_DECK_ENV'
API_SERVER_ENABLED=true
API_SERVER_HOST=0.0.0.0
API_SERVER_PORT=8642
API_SERVER_KEY=${o.apiServerKey}
${o.providerEnv}=${o.providerKey}
HERMES_DECK_ENV
cat "$merged" > "$ENV_FILE"
rm -f "$merged"
echo "Updated $ENV_FILE (secrets are not printed)."

step pull
docker pull "$HD_IMAGE"

step configure
docker run --rm -v "$HD_DATA_DIR:/opt/data" "$HD_IMAGE" config set model.provider ${shq(o.providerId)}
docker run --rm -v "$HD_DATA_DIR:/opt/data" "$HD_IMAGE" config set model.default ${shq(o.model)}
echo "Model: ${o.providerId} / ${o.model}"
${startAndWait()}`;
}

/** Pull the newest image and recreate the container with the existing data directory. */
export function buildDockerUpdateScript(o: Pick<DockerDeployOptions, 'container' | 'dataDir' | 'hostPort' | 'imageTag'>): string {
  return `${prelude(o)}
step pull
docker pull "$HD_IMAGE"
${startAndWait()}`;
}

export type ManageAction = 'status' | 'logs' | 'restart' | 'stop' | 'start' | 'doctor' | 'remove';

/** One-line management commands; they run through {@link asRoot}. */
export function manageCommand(action: ManageAction, container: string): string {
  if (!CONTAINER_NAME.test(container)) throw new Error('Invalid container name.');
  const c = shq(container);
  switch (action) {
    case 'status':
      return `docker inspect -f '{{.State.Status}}|{{.State.StartedAt}}|{{.Config.Image}}|{{.RestartCount}}' ${c} 2>/dev/null || echo 'missing|||'`;
    case 'logs':
      return `docker logs --tail 300 ${c} 2>&1`;
    case 'restart':
      return `docker restart ${c}`;
    case 'stop':
      return `docker stop ${c}`;
    case 'start':
      return `docker start ${c}`;
    case 'doctor':
      return `docker exec ${c} hermes doctor 2>&1`;
    case 'remove':
      return `docker rm -f ${c}`;
  }
}

export interface ContainerStatus {
  state: 'running' | 'exited' | 'restarting' | 'paused' | 'created' | 'missing' | 'unknown';
  startedAt?: string;
  image?: string;
  restarts?: number;
}

export function parseContainerStatus(output: string): ContainerStatus {
  const line = output.trim().split('\n').pop() ?? '';
  const [state, startedAt, image, restarts] = line.split('|');
  const known = ['running', 'exited', 'restarting', 'paused', 'created', 'missing'];
  return {
    state: (known.includes(state) ? state : 'unknown') as ContainerStatus['state'],
    startedAt: startedAt || undefined,
    image: image || undefined,
    restarts: restarts ? Number(restarts) : undefined,
  };
}

export type Privilege = { kind: 'root' } | { kind: 'sudo'; password?: string };

/**
 * Wraps a command so it runs as root. The sudo password travels on stdin (never in argv), and the
 * command's own stdin is detached so nothing downstream can read the password line.
 */
export function asRoot(command: string, privilege: Privilege): { command: string; stdin?: string } {
  if (privilege.kind === 'root') return { command };
  const inner = shq(`exec </dev/null; ${command}`);
  if (privilege.password) {
    return { command: `sudo -S -p '' sh -c ${inner}`, stdin: `${privilege.password}\n` };
  }
  return { command: `sudo -n sh -c ${inner}` };
}

/** Where the generated script is staged on the server. Owner-only, deleted after it runs. */
export const REMOTE_SCRIPT_DIR = '$HOME/.hermes-deck';

export function stageScriptCommand(name: string): string {
  return `umask 077 && mkdir -p "${REMOTE_SCRIPT_DIR}" && cat > "${REMOTE_SCRIPT_DIR}/${name}"`;
}

export function runStagedScriptCommand(name: string, privilege: Privilege): { command: string; stdin?: string } {
  const path = `"${REMOTE_SCRIPT_DIR}/${name}"`;
  const cleanup = `rc=$?; rm -f ${path}; exit $rc`;
  if (privilege.kind === 'root') return { command: `bash ${path}; ${cleanup}` };
  if (privilege.password) {
    return { command: `sudo -S -p '' bash ${path}; ${cleanup}`, stdin: `${privilege.password}\n` };
  }
  return { command: `sudo -n bash ${path}; ${cleanup}` };
}
