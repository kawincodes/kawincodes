#!/usr/bin/env python3
"""Generate the KRS Tunnels logo as Android vector drawables.

Outputs (app/src/main/res/drawable/):
  ic_launcher_background.xml  orange gradient with faint radar rings (adaptive icon background)
  ic_launcher_foreground.xml  emblem: tunnel arch + radar + cloud keystone + "KRS" monogram
  ic_launcher_monochrome.xml  single-color emblem for Android 13+ themed icons
  logo_mark.xml               emblem on an orange rounded square (in-app use)
  logo_lockup.xml             horizontal lockup: mark, "KRS TUNNELS", tagline, maker line

Usage (fonts: Space Grotesk 500/700 from the @fontsource/space-grotesk npm package, OFL-1.1):
  python3 tools/brand/build_logo.py <SpaceGrotesk-700.woff> <SpaceGrotesk-500.woff>
Requires fonttools.
"""
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from textpath import TextPath  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DRAWABLE = os.path.join(ROOT, "app", "src", "main", "res", "drawable")

ORANGE_LIGHT = "#FFFFB054"
ORANGE = "#FFF6821F"
ORANGE_DEEP = "#FFC2410C"
WHITE = "#FFFFFFFF"
INK = "#FF05070D"

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/brand/build_logo.py - edit the script, not this file. -->\n')
NS = ('xmlns:android="http://schemas.android.com/apk/res/android"\n'
      '    xmlns:aapt="http://schemas.android.com/aapt"')


def r(d):
    """Round numbers in path data to 2 decimals."""
    return re.sub(r"-?\d+\.\d+", lambda m: ("%.2f" % float(m.group())).rstrip("0").rstrip("."), d)


def path(d, fill=None, stroke=None, width=None, cap="round", join="round"):
    a = [f'android:pathData="{r(d)}"']
    a.append(f'android:fillColor="{fill or "#00000000"}"')
    if stroke:
        a += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{width}"',
              f'android:strokeLineCap="{cap}"', f'android:strokeLineJoin="{join}"']
    return "<path " + " ".join(a) + " />"


def gradient_path(d, kind, stops, **geo):
    attrs = " ".join(f'android:{k}="{v}"' for k, v in geo.items())
    items = "".join(f'<item android:color="{c}" android:offset="{o}" />' for o, c in stops)
    return (f'<path android:pathData="{r(d)}"><aapt:attr name="android:fillColor">'
            f'<gradient android:type="{kind}" {attrs}>{items}</gradient></aapt:attr></path>')


def vector(w, h, body, vw=None, vh=None):
    return (HEADER + f'<vector {NS}\n    android:width="{w}dp"\n    android:height="{h}dp"\n'
            f'    android:viewportWidth="{vw or w}"\n    android:viewportHeight="{vh or h}">\n    '
            + "\n    ".join(body) + "\n</vector>\n")


def circle(cx, cy, rad):
    return f"M{cx - rad},{cy} a{rad},{rad} 0 1,0 {2 * rad},0 a{rad},{rad} 0 1,0 {-2 * rad},0"


def polar(cx, cy, rad, deg):
    t = math.radians(deg)
    return cx + rad * math.cos(t), cy + rad * math.sin(t)


def emblem(bold, ink, soft):
    """Emblem in the 108x108 adaptive-icon space (safe zone: circle r=33 around 54,54).

    ink: main color; soft: translucent variant of it (radar sweep and inner ring).
    """
    cx, cy, rr = 54.0, 56.5, 12.5          # radar
    lead = polar(cx, cy, rr, -28)
    tail = polar(cx, cy, rr, -95)
    sweep = f"M{cx},{cy} L{tail[0]},{tail[1]} A{rr},{rr} 0 0 1 {lead[0]},{lead[1]} Z"
    blip1 = polar(cx, cy, 8.6, -62)
    blip2 = polar(cx, cy, 10.2, 148)
    # Lucide "cloud" (ISC: M17.5 19H9a7 7 0 1 1 6.71-9h1.79a4.5 4.5 0 1 1 0 9Z), filled and
    # scaled into place as the arch keystone: the Cloudflare edge above the tunnel.
    s, tx, ty = 0.82, 54 - 12.3 * 0.82, 27.6 - 12.4 * 0.82
    cloud = (f"M{17.5 * s + tx},{19 * s + ty} H{9 * s + tx} "
             f"a{7 * s},{7 * s} 0 1 1 {6.71 * s},{-9 * s} h{1.79 * s} "
             f"a{4.5 * s},{4.5 * s} 0 1 1 0,{9 * s} Z")
    return [
        # Tunnel portal and road.
        path("M31.5,73 V51.5 A22.5,22.5 0 0 1 76.5,51.5 V73", stroke=ink, width=4.4),
        path("M27.5,73.4 H80.5", stroke=ink, width=3.2),
        # Radar inside the tunnel.
        path(sweep, fill=soft),
        path(circle(cx, cy, rr), stroke=ink, width=2.0),
        path(circle(cx, cy, 6.6), stroke=soft, width=1.8),
        path(f"M{cx},{cy} L{lead[0]},{lead[1]}", stroke=ink, width=2.2),
        path(circle(cx, cy, 2.3), fill=ink),
        path(circle(*blip1, 1.7), fill=ink),
        path(circle(*blip2, 1.35), fill=ink),
        # Cloud keystone.
        path(cloud, fill=ink),
        # Monogram.
        path(bold.path("KRS", 54, 85.6, 8.2, tracking=1.1, anchor="middle"), fill=ink),
    ]


def launcher(paths):
    """Shrink the emblem so masks never clip it (keeps it well inside the 66 dp safe zone)."""
    return ['<group android:pivotX="54" android:pivotY="54" android:scaleX="0.8" android:scaleY="0.8">',
            *paths, "</group>"]


def background():
    sq = "M0,0h108v108h-108z"
    rings = [path(circle(54, 54, rad), stroke="#1FFFFFFF", width=0.8) for rad in (26, 38, 50)]
    return [
        gradient_path(sq, "linear", [(0, ORANGE_LIGHT), (0.55, ORANGE), (1, ORANGE_DEEP)],
                      startX=0, startY=0, endX=108, endY=108),
        gradient_path(sq, "radial", [(0, "#38FFFFFF"), (1, "#00FFFFFF")],
                      centerX=36, centerY=30, gradientRadius=64),
        *rings,
        path("M54,4 V104 M4,54 H104", stroke="#14FFFFFF", width=0.6),
    ]


def mark(bold, size=108):
    """Emblem on an orange rounded square, as a standalone in-app drawable."""
    sq = "M22,4 H86 A18,18 0 0 1 104,22 V86 A18,18 0 0 1 86,104 H22 A18,18 0 0 1 4,86 V22 A18,18 0 0 1 22,4 Z"
    body = [
        gradient_path(sq, "linear", [(0, ORANGE_LIGHT), (0.55, ORANGE), (1, ORANGE_DEEP)],
                      startX=4, startY=4, endX=104, endY=104),
        gradient_path(sq, "radial", [(0, "#33FFFFFF"), (1, "#00FFFFFF")],
                      centerX=36, centerY=30, gradientRadius=64),
        '<group android:pivotX="54" android:pivotY="54" android:scaleX="1.18" android:scaleY="1.18">',
        *emblem(bold, WHITE, "#59FFFFFF"),
        "</group>",
    ]
    return vector(size, size, body, 108, 108)


def lockup(bold, medium):
    """Horizontal lockup, 640x200 viewport, transparent background (for dark surfaces)."""
    body = [
        '<group android:translateX="20" android:translateY="20" android:scaleX="1.48" android:scaleY="1.48">',
    ]
    # Reuse the mark's content inside a 108 box scaled to 160.
    sq = "M22,4 H86 A18,18 0 0 1 104,22 V86 A18,18 0 0 1 86,104 H22 A18,18 0 0 1 4,86 V22 A18,18 0 0 1 22,4 Z"
    body += [
        gradient_path(sq, "linear", [(0, ORANGE_LIGHT), (0.55, ORANGE), (1, ORANGE_DEEP)],
                      startX=4, startY=4, endX=104, endY=104),
        gradient_path(sq, "radial", [(0, "#33FFFFFF"), (1, "#00FFFFFF")],
                      centerX=36, centerY=30, gradientRadius=64),
        '<group android:pivotX="54" android:pivotY="54" android:scaleX="1.18" android:scaleY="1.18">',
        *emblem(bold, WHITE, "#59FFFFFF"),
        "</group>", "</group>",
    ]
    x, span = 214, 404
    # Fit "KRS TUNNELS" exactly to the divider width.
    cap = 46.0
    total = bold.width("KRS", cap, 2) + 16 + bold.width("TUNNELS", cap, 2)
    cap *= span / total
    krs_w = bold.width("KRS", cap, 2)
    body += [
        path(bold.path("KRS", x, 92, cap, tracking=2), fill=ORANGE),
        path(bold.path("TUNNELS", x + krs_w + 16 * cap / 46, 92, cap, tracking=2), fill="#FFE6EDF3"),
        path(medium.path("Cloudflare Tunnels  ·  Radar  ·  Chat", x + 1, 128, 15.5, tracking=0.6),
             fill="#FF8B98A9"),
        path("M%s,146 H%s" % (x + 1, x + span), stroke="#FF1F2A3A", width=1.2, cap="butt"),
        path(medium.path("BY KRS TECH SOLUTIONS", x + 1, 172, 10.5, tracking=2.6), fill="#FFFFAD5C"),
        path(medium.path("ANDROID", x + span, 172, 10.5, tracking=2.6, anchor="end"), fill="#FF5B6B7F"),
    ]
    return vector(640, 200, body)


def main():
    bold, medium = TextPath(sys.argv[1]), TextPath(sys.argv[2])
    files = {
        "ic_launcher_background.xml": vector(108, 108, background()),
        "ic_launcher_foreground.xml": vector(108, 108, launcher(emblem(bold, WHITE, "#59FFFFFF"))),
        "ic_launcher_monochrome.xml": vector(108, 108, launcher(emblem(bold, WHITE, "#80FFFFFF"))),
        "logo_mark.xml": mark(bold),
        "logo_lockup.xml": lockup(bold, medium),
    }
    for name, xml in files.items():
        with open(os.path.join(DRAWABLE, name), "w") as f:
            f.write(xml)
        print("wrote", name, len(xml), "bytes")


if __name__ == "__main__":
    main()
