#!/usr/bin/env python3
"""Generate the KRS Tunnels logo as Android vector drawables.

The symbol is "Cloud Gate": a cloud with a tunnel doorway cut into it - a tunnel into
Cloudflare. The wordmark is "KRS TUNNELS" with the single tagline "Cloudflare Tunnels".

Outputs (app/src/main/res/drawable/):
  ic_launcher_background.xml  orange gradient (adaptive icon background)
  ic_launcher_foreground.xml  the Cloud Gate symbol in white
  ic_launcher_monochrome.xml  the symbol for Android 13+ themed icons
  logo_mark.xml               symbol on an orange rounded square (in-app use)
  logo_lockup.xml             mark + "KRS TUNNELS" + "Cloudflare Tunnels"

Usage (fonts: Space Grotesk 500/700 from the @fontsource/space-grotesk npm package, OFL-1.1):
  python3 tools/brand/build_logo.py <SpaceGrotesk-700.woff> <SpaceGrotesk-500.woff>
Requires fonttools.
"""
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from textpath import TextPath  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DRAWABLE = os.path.join(ROOT, "app", "src", "main", "res", "drawable")

ORANGE_LIGHT = "#FFFFB054"
ORANGE = "#FFF6821F"
ORANGE_DEEP = "#FFC2410C"
WHITE = "#FFFFFFFF"
TEXT = "#FFE6EDF3"
MUTED = "#FF8B98A9"

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/brand/build_logo.py - edit the script, not this file. -->\n')
NS = ('xmlns:android="http://schemas.android.com/apk/res/android"\n'
      '    xmlns:aapt="http://schemas.android.com/aapt"')

# Cloud built from three circles (left, middle, right) on a flat base, in the 108x108 icon space.
CLOUD_L = (39.0, 59.5, 8.5)
CLOUD_M = (53.5, 50.5, 13.5)
CLOUD_R = (68.5, 57.5, 10.5)
CLOUD_BASE = 68.0
SQUARE = "M22,4 H86 A18,18 0 0 1 104,22 V86 A18,18 0 0 1 86,104 H22 A18,18 0 0 1 4,86 V22 A18,18 0 0 1 22,4 Z"


def r(d):
    """Round numbers in path data to 2 decimals."""
    return re.sub(r"-?\d+\.\d+", lambda m: ("%.2f" % float(m.group())).rstrip("0").rstrip("."), d)


def path(d, fill, even_odd=False):
    a = f'android:fillColor="{fill}" android:pathData="{r(d)}"'
    if even_odd:
        a += ' android:fillType="evenOdd"'
    return f"<path {a} />"


def gradient_path(d, kind, stops, **geo):
    attrs = " ".join(f'android:{k}="{v}"' for k, v in geo.items())
    items = "".join(f'<item android:color="{c}" android:offset="{o}" />' for o, c in stops)
    return (f'<path android:pathData="{r(d)}"><aapt:attr name="android:fillColor">'
            f'<gradient android:type="{kind}" {attrs}>{items}</gradient></aapt:attr></path>')


def vector(w, h, body, vw=None, vh=None):
    return (HEADER + f'<vector {NS}\n    android:width="{w}dp"\n    android:height="{h}dp"\n'
            f'    android:viewportWidth="{vw or w}"\n    android:viewportHeight="{vh or h}">\n    '
            + "\n    ".join(body) + "\n</vector>\n")


def group(body, scale=1.0, tx=0.0, ty=0.0, pivot=(54, 54)):
    """Android group: p -> (p - pivot) * scale + pivot + translate."""
    return ([f'<group android:pivotX="{pivot[0]}" android:pivotY="{pivot[1]}" android:scaleX="{scale}" '
             f'android:scaleY="{scale}" android:translateX="{round(tx, 3)}" android:translateY="{round(ty, 3)}">']
            + body + ["</group>"])


def _upper_intersection(c1, c2):
    (x1, y1, r1), (x2, y2, r2) = c1, c2
    d = math.hypot(x2 - x1, y2 - y1)
    a = (r1 * r1 - r2 * r2 + d * d) / (2 * d)
    h = math.sqrt(r1 * r1 - a * a)
    xm, ym = x1 + a * (x2 - x1) / d, y1 + a * (y2 - y1) / d
    pts = [(xm + h * (y2 - y1) / d, ym - h * (x2 - x1) / d), (xm - h * (y2 - y1) / d, ym + h * (x2 - x1) / d)]
    return min(pts, key=lambda p: p[1])


def _large_arc(c, start, end):
    """large-arc flag for a clockwise (screen) arc on circle c from start to end."""
    a0 = math.degrees(math.atan2(start[1] - c[1], start[0] - c[0])) % 360
    a1 = math.degrees(math.atan2(end[1] - c[1], end[0] - c[0])) % 360
    return 1 if (a1 - a0) % 360 > 180 else 0


def cloud_gate():
    """Cloud outline plus the tunnel doorway (filled even-odd so the door is a hole)."""
    lm, mr = _upper_intersection(CLOUD_L, CLOUD_M), _upper_intersection(CLOUD_M, CLOUD_R)
    lb, rb = (CLOUD_L[0], CLOUD_BASE), (CLOUD_R[0], CLOUD_BASE)
    cloud = (f"M{lb[0]},{lb[1]} "
             f"A{CLOUD_L[2]},{CLOUD_L[2]} 0 {_large_arc(CLOUD_L, lb, lm)} 1 {lm[0]},{lm[1]} "
             f"A{CLOUD_M[2]},{CLOUD_M[2]} 0 {_large_arc(CLOUD_M, lm, mr)} 1 {mr[0]},{mr[1]} "
             f"A{CLOUD_R[2]},{CLOUD_R[2]} 0 {_large_arc(CLOUD_R, mr, rb)} 1 {rb[0]},{rb[1]} Z")
    door_w, door_h = 13.0, 15.5
    x0, x1, top = 54 - door_w / 2, 54 + door_w / 2, CLOUD_BASE - door_h + door_w / 2
    door = f"M{x0},{CLOUD_BASE} V{top} A{door_w / 2},{door_w / 2} 0 0 1 {x1},{top} V{CLOUD_BASE} Z"
    return cloud + " " + door


def symbol(ink):
    """The Cloud Gate symbol, optically centred in the 108 space, with a light in the doorway."""
    light = "M52.1,63.6 a1.9,1.9 0 1,0 3.8,0 a1.9,1.9 0 1,0 -3.8,0"
    return group([path(cloud_gate(), ink, even_odd=True), path(light, ink)], ty=-1.2)


def orange_fill(d, x0=0, y0=0, x1=108, y1=108):
    return [
        gradient_path(d, "linear", [(0, ORANGE_LIGHT), (0.55, ORANGE), (1, ORANGE_DEEP)],
                      startX=x0, startY=y0, endX=x1, endY=y1),
        gradient_path(d, "radial", [(0, "#38FFFFFF"), (1, "#00FFFFFF")],
                      centerX=round(x0 + (x1 - x0) * 0.32, 2), centerY=round(y0 + (y1 - y0) * 0.26, 2),
                      gradientRadius=round((x1 - x0) * 0.62, 2)),
    ]


def mark_body():
    """Orange rounded square (4..104) with the symbol, in the 108 space."""
    return orange_fill(SQUARE, 4, 4, 104, 104) + group(symbol(WHITE), scale=1.32)


def lockup(bold, medium):
    """Mark + "KRS TUNNELS" + "Cloudflare Tunnels" in a 560x160 viewport (for dark surfaces)."""
    s = 1.28                      # the 100-unit square becomes 128 px, placed at (16, 16)
    body = group(mark_body(), scale=s, tx=16 - 4 * s, ty=16 - 4 * s, pivot=(0, 0))
    x, span, cap = 172, 372, 44.0
    total = bold.width("KRS", cap, 2) + 15 + bold.width("TUNNELS", cap, 2)
    cap *= span / total
    krs_w = bold.width("KRS", cap, 2)
    body += [
        path(bold.path("KRS", x, 84, cap, tracking=2), ORANGE),
        path(bold.path("TUNNELS", x + krs_w + 15 * cap / 44, 84, cap, tracking=2), TEXT),
        path(medium.path("Cloudflare Tunnels", x + 1, 121, 17, tracking=1.2), MUTED),
    ]
    return vector(560, 160, body)


def main():
    bold, medium = TextPath(sys.argv[1]), TextPath(sys.argv[2])
    files = {
        "ic_launcher_background.xml": vector(108, 108, orange_fill("M0,0h108v108h-108z")),
        "ic_launcher_foreground.xml": vector(108, 108, symbol(WHITE)),
        "ic_launcher_monochrome.xml": vector(108, 108, symbol(WHITE)),
        "logo_mark.xml": vector(108, 108, mark_body()),
        "logo_lockup.xml": lockup(bold, medium),
    }
    for name, xml in files.items():
        with open(os.path.join(DRAWABLE, name), "w") as f:
            f.write(xml)
        print("wrote", name, len(xml), "bytes")


if __name__ == "__main__":
    main()
